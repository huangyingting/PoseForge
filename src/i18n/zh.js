function subject(text, api) {
  const parts = /^([\w.]+) (?:to|and) ([\w.]+)$/.exec(text);
  if (parts && /^[a-z]/.test(parts[1])) return `${landmark(parts[1], api)}与${landmark(parts[2], api)}`;
  return text.split(" and ").join(" 与 ");
}

